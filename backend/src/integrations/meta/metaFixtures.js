function isoDateDaysAgo(daysAgo) {
  const now = new Date();
  const utc = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() - daysAgo));
  return utc.toISOString().slice(0, 10);
}

